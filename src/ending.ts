    + '<p>これで誰もが同じ立場になったわけではない。恒久的な議席変更は、これからの話し合いに委ねられた。ヴェスク、トマ、リセも、それぞれ何を知り、何をしたのかを審理で問われる。人を救ったことだけで、過去の責任が帳消しになるわけではなかった。</p>'

function dialogueHtml(lines: readonly DialogueLine[], scene: string): string {
  return lines.map(({ speaker, text }) => `<blockquote data-story-addition="${scene}">${speaker}「${text}」</blockquote>`).join('');
}
export function battleDialogueHtml(battleId: BattleId, phase: 'intro' | 'result'): string {
  return dialogueHtml(BATTLE_DIALOGUE[battleId][phase], `${battleId}:${phase}`);
}
export function endingDialogueHtml(part: 'safety' | 'vote' | 'responsibility' | 'measurement'): string {
  const bounds = { safety: [0, 2], vote: [2, 6], responsibility: [6, 9], measurement: [9, 14] } as const;
  return dialogueHtml(ENDING_DIALOGUE.slice(...bounds[part]), `ending:${part}`);
}
